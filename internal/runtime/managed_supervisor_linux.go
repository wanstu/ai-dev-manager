//go:build linux

package runtime

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	goruntime "runtime"
	"sync"
	"syscall"
	"time"

	"golang.org/x/sys/unix"
)

const managedSupervisorArg = "--adm-internal-process-supervisor-v1"

type supervisorReady struct {
	PID   int    `json:"pid"`
	Start uint64 `json:"start"`
	Error string `json:"error,omitempty"`
}

// Re-execute the same ADM binary (including desktop and test executables).
// This private mode has no elevated privileges and no gateway access.
// It receives only a pre-authorized command and two inherited pipe handles.
func init() {
	if len(os.Args) >= 4 && os.Args[1] == managedSupervisorArg {
		os.Exit(runManagedSupervisor(os.Args[2], os.Args[3:]))
	}
}

func runManagedSupervisor(path string, args []string) int {
	// Linux Pdeathsig tracks the launching OS thread, not just the process.
	goruntime.LockOSThread()
	defer goruntime.UnlockOSThread()
	control := os.NewFile(3, "adm-owner-control")
	ready := os.NewFile(4, "adm-supervisor-ready")
	if control == nil || ready == nil {
		return 125
	}
	defer control.Close()
	defer ready.Close()
	for _, f := range []*os.File{control, ready} {
		info, err := f.Stat()
		if err != nil || info.Mode()&os.ModeNamedPipe == 0 {
			return 125
		}
		unix.CloseOnExec(int(f.Fd()))
	}
	report := func(r supervisorReady) { _ = json.NewEncoder(ready).Encode(r); _ = ready.Close() }
	if !filepath.IsAbs(path) || len(args) == 0 {
		report(supervisorReady{Error: "invalid prepared command"})
		return 125
	}
	// Adopt orphaned descendants so killed group members do not remain zombies
	// under an init process that does not reap them (e.g. some containers).
	if err := unix.Prctl(unix.PR_SET_CHILD_SUBREAPER, 1, 0, 0, 0); err != nil {
		report(supervisorReady{Error: "enable child subreaper: " + err.Error()})
		return 125
	}
	child := &exec.Cmd{Path: path, Args: args, Stdin: os.Stdin, Stdout: os.Stdout, Stderr: os.Stderr,
		SysProcAttr: &syscall.SysProcAttr{Setpgid: true, Pdeathsig: syscall.SIGKILL}}
	// EOF is generated by the kernel even when the owner is SIGKILLed.
	ownerGone := make(chan struct{})
	go func() { _, _ = io.Copy(io.Discard, control); close(ownerGone) }()
	select {
	case <-ownerGone:
		report(supervisorReady{Error: "owner disconnected"})
		return 125
	default:
	}
	if err := child.Start(); err != nil {
		report(supervisorReady{Error: err.Error()})
		return 125
	}
	pid := child.Process.Pid
	stat, err := readLinuxProcessStat(pid)
	if err != nil || stat.group != pid {
		_ = child.Process.Kill()
		_ = child.Wait()
		report(supervisorReady{Error: "cannot verify managed process group"})
		return 125
	}
	report(supervisorReady{PID: pid, Start: stat.start})
	// WNOWAIT retains the direct child's PID until group termination has
	// completed, avoiding a recycled group ID being signalled after reaping.
	done := make(chan error, 1)
	go func() {
		var info unix.Siginfo
		for {
			err := unix.Waitid(unix.P_PID, pid, &info, unix.WEXITED|unix.WNOWAIT, nil)
			if errors.Is(err, unix.EINTR) {
				continue
			}
			done <- err
			return
		}
	}()
	select {
	case <-ownerGone:
		_ = unix.Kill(-pid, unix.SIGKILL)
		<-done
	case err := <-done:
		if err != nil {
			_ = child.Process.Kill()
			_ = child.Wait()
			return 125
		}
	}
	// The leader is still a zombie or live direct child. All members of this
	// managed group are terminated before Wait releases its numeric identity.
	_ = unix.Kill(-pid, unix.SIGKILL)
	err = child.Wait()
	reapManagedDescendants()
	if err == nil {
		return 0
	}
	if child.ProcessState != nil {
		if status, ok := child.ProcessState.Sys().(syscall.WaitStatus); ok && status.Signaled() {
			return 128 + int(status.Signal())
		}
		if code := child.ProcessState.ExitCode(); code >= 0 {
			return code
		}
	}
	return 125
}

// Only reap this supervisor's own adopted descendants. A process that
// intentionally escapes the group is not considered safely contained.
func reapManagedDescendants() {
	deadline := time.Now().Add(500 * time.Millisecond)
	for {
		var status unix.WaitStatus
		pid, err := unix.Wait4(-1, &status, unix.WNOHANG, nil)
		if errors.Is(err, unix.EINTR) {
			continue
		}
		if err != nil {
			return
		}
		if pid > 0 {
			continue
		}
		if time.Now().After(deadline) {
			return
		}
		time.Sleep(10 * time.Millisecond)
	}
}

func startSupervisedLinuxProcess(cmd *exec.Cmd) (ManagedProcess, error) {
	if len(cmd.ExtraFiles) != 0 {
		return nil, fmt.Errorf("managed Linux Process does not accept extra inherited files")
	}
	executable, err := os.Executable()
	if err != nil {
		return nil, err
	}
	path := cmd.Path
	if !filepath.IsAbs(path) {
		base := cmd.Dir
		if base == "" {
			base, err = os.Getwd()
			if err != nil {
				return nil, err
			}
		}
		path = filepath.Join(base, path)
	}
	controlRead, controlWrite, err := os.Pipe()
	if err != nil {
		return nil, err
	}
	defer controlRead.Close()
	readyRead, readyWrite, err := os.Pipe()
	if err != nil {
		controlWrite.Close()
		return nil, err
	}
	defer readyRead.Close()
	defer readyWrite.Close()
	var once sync.Once
	stop := func() { once.Do(func() { _ = controlWrite.Close() }) }
	originalArgs := append([]string(nil), cmd.Args...)
	cmd.Path = executable
	cmd.Args = append([]string{executable, managedSupervisorArg, path}, originalArgs...)
	cmd.ExtraFiles = []*os.File{controlRead, readyWrite}
	// The supervisor must survive cancellation long enough to clean its group.
	// It exits on control pipe EOF; do not signal its PID/group directly.
	cmd.SysProcAttr = &syscall.SysProcAttr{Setpgid: true}
	if cmd.Cancel != nil {
		cmd.Cancel = func() error { stop(); return nil }
	}
	if err := cmd.Start(); err != nil {
		stop()
		return nil, err
	}
	controlRead.Close()
	readyWrite.Close()
	_ = readyRead.SetReadDeadline(time.Now().Add(5 * time.Second))
	var info supervisorReady
	err = json.NewDecoder(io.LimitReader(readyRead, 8192)).Decode(&info)
	if err != nil || info.Error != "" || info.PID <= 0 || info.Start == 0 {
		stop()
		_ = cmd.Wait()
		return nil, fmt.Errorf("managed process launch failed: %s (%v)", info.Error, err)
	}
	return &linuxManagedProcess{pid: info.PID, start: info.Start, stop: stop}, nil
}
